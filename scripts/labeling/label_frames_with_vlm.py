def label_frames_in_directory(frame_dir, output_dir):
    """
    Iterates through frames in a directory, calls VLM for analysis,
    and saves the result as a CroissantML JSON file.
    """
    if not os.path.isdir(frame_dir):
        print(f"Directory not found: {frame_dir}")
        return

    frames = sorted([f for f in os.listdir(frame_dir) if f.lower().endswith(('.jpg', '.jpeg', '.png'))])
    
    if not frames:
        return

    video_name = os.path.basename(frame_dir)
    json_output_dir = os.path.join(output_dir, video_name)
    os.makedirs(json_output_dir, exist_ok=True)

    for frame_name in tqdm(frames, desc=f"Labeling frames for {video_name}"):
        frame_path = os.path.join(frame_dir, frame_name)
        
        # Call the VLM to get analysis
        vlm_analysis = call_vlm_api(frame_path)
        
        # Create the Croissant record
        croissant_record = create_croissant_record_for_frame(frame_path, vlm_analysis)
        
        # Save the record to a JSON file
        json_filename = os.path.splitext(frame_name)[0] + ".json"
        json_output_path = os.path.join(json_output_dir, json_filename)
        save_json(croissant_record, json_output_path)
        
    print(f"Finished labeling for {video_name}. JSON files saved in {json_output_dir}")

def main():
    parser = argparse.ArgumentParser(description="Label video frames using a VLM and save as CroissantML JSON.")
    parser.add_argument("--frames_dir", type=str, default="data/frames", help="Directory containing subdirectories of frames.")
    parser.add_argument("--output_dir", type=str, default="data/croissant_data/frames", help="Directory to save the output JSON files.")
    args = parser.parse_args()

    frame_subdirs = [d for d in os.listdir(args.frames_dir) if os.path.isdir(os.path.join(args.frames_dir, d))]

    if not frame_subdirs:
        print(f"No frame directories found in {args.frames_dir}. Please run the preprocessing script first.")
        return

    for video_dir_name in frame_subdirs:
        full_path = os.path.join(args.frames_dir, video_dir_name)
        label_frames_in_directory(full_path, args.output_dir)

if __name__ == "__main__":
    main()